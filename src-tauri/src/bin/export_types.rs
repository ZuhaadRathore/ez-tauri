//! Binary to export TypeScript types from Rust Tauri commands.
//!
//! Run this with: cargo run --bin export_types

use ez_tauri_lib::*;
use tauri_specta::ts;

fn main() {
    let builder = ts::builder()
        .commands(tauri_specta::collect_commands![
            // Rate-limited handlers
            handlers::rate_limited::rl_greet,
            handlers::rate_limited::rl_check_database_connection,
            handlers::rate_limited::rl_initialize_database,
            handlers::rate_limited::rl_run_migrations,
            handlers::rate_limited::rl_get_all_users,
            handlers::rate_limited::rl_get_user_by_id,
            handlers::rate_limited::rl_create_user,
            handlers::rate_limited::rl_update_user,
            handlers::rate_limited::rl_delete_user,
            handlers::rate_limited::rl_authenticate_user,
            handlers::rate_limited::rl_create_log,
            handlers::rate_limited::rl_get_logs,
            handlers::rate_limited::rl_delete_old_logs,
            handlers::rate_limited::rl_get_system_info,
            handlers::rate_limited::rl_send_notification,
            handlers::rate_limited::rl_get_window_info,
            handlers::rate_limited::rl_toggle_window_maximize,
            handlers::rate_limited::rl_minimize_window,
            handlers::rate_limited::rl_center_window,
            handlers::rate_limited::rl_set_window_title,
            handlers::rate_limited::rl_create_new_window,
            handlers::rate_limited::rl_execute_command,
            handlers::rate_limited::rl_get_app_data_dir,
            handlers::rate_limited::rl_get_app_log_dir,
            handlers::rate_limited::rl_read_text_file,
            handlers::rate_limited::rl_write_text_file,
            handlers::rate_limited::rl_append_text_file,
            handlers::rate_limited::rl_delete_file,
            handlers::rate_limited::rl_create_directory,
            handlers::rate_limited::rl_list_directory,
            handlers::rate_limited::rl_file_exists,
            handlers::rate_limited::rl_get_file_info,
            handlers::rate_limited::rl_copy_file,
            handlers::rate_limited::rl_move_file,
            handlers::rate_limited::rl_get_log_config,
            handlers::rate_limited::rl_update_log_config,
            handlers::rate_limited::rl_get_log_entries,
            handlers::rate_limited::rl_clear_old_logs,
            handlers::rate_limited::rl_get_log_stats,
            handlers::rate_limited::rl_create_test_log,
            handlers::rate_limited::rl_set_cache_value,
            handlers::rate_limited::rl_get_cache_value,
            handlers::rate_limited::rl_delete_cache_value,
            handlers::rate_limited::rl_cache_key_exists,
            handlers::rate_limited::rl_is_cache_available,
            handlers::rate_limited::get_rate_limiter_status,
            // Authentication commands
            modules::auth::auth_register,
            modules::auth::auth_login,
            modules::auth::auth_logout,
            modules::auth::auth_logout_all,
            modules::auth::auth_refresh_token,
            modules::auth::auth_verify_token,
            modules::auth::auth_get_sessions,
            modules::auth::auth_revoke_session,
        ])
        .header("// This file was generated by Tauri Specta. DO NOT EDIT THIS FILE MANUALLY.")
        .config(
            specta::ts::ExportConfig::default()
                .bigint(specta::ts::BigIntExportBehavior::Number)
        );

    #[cfg(debug_assertions)]
    builder
        .export(
            specta::ts::ExportConfig::default(),
            "../src/types/bindings.ts",
        )
        .expect("Failed to export TypeScript bindings");

    println!("TypeScript bindings exported successfully to src/types/bindings.ts");
}
